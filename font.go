// wrapText splits msg into lines of at most maxCols glyphs; longer words get a line of their own.
func wrapText(msg string, maxCols int) [][]rune {
	var lines [][]rune
	var cur []rune
	for _, word := range strings.Fields(fold.Replace(strings.ToUpper(msg))) {
		wr := []rune(word)
		if len(cur) > 0 && len(cur)+1+len(wr) > maxCols {
			lines = append(lines, cur)
			cur = nil
		}
		if len(cur) > 0 {
			cur = append(cur, ' ')
		}
		cur = append(cur, wr...)
	}
	if len(cur) > 0 {
		lines = append(lines, cur)
	}
	return lines
}
